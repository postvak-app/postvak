/// Opens the window and returns when it closes. When it cannot start, a small window says why before the error is
/// returned, since a launch from a desktop entry or Finder has no terminal for stderr. When no window can open, it
/// tries once more with the software renderer. Safe mode, asked for or after two starts in a row that died before
/// the window showed, draws in software and ignores the saved layout. With a window already open, this start hands
/// it `open` and returns: that window comes to the front, showing the message.
pub fn run(
    paths: Result<Paths>,
    safe_mode: bool,
    show: Option<Show>,
    background: bool,
) -> Result<()> {
    phases::start();
    let token = launch::take_token();
    let instance = match &paths {
        Ok(paths) => match instance::claim(paths, &instance::Request { show: show.clone() }) {
            instance::Claim::Handed => return Ok(()),
            instance::Claim::First(instance) => Some(instance),
            instance::Claim::Alone => None,
        },
        Err(_) => None,
    };
    let marker = paths
        .as_ref()
        .ok()
        .map(|paths| launch::Marker::new(&paths.state_dir));
    let failed_starts = marker.as_ref().map_or(0, launch::Marker::failed_starts);
    let safe_mode = launch::safe_mode(safe_mode, failed_starts);
    if safe_mode {
        log::warn!("safe mode: the software renderer and the default window layout");
    }
    if let Some(marker) = &marker {
        marker.set(failed_starts + 1);
    }
    let backend = std::env::var("SLINT_BACKEND").ok();
    let renderer = launch::renderer(safe_mode, backend.as_deref());
    launch::select(renderer, APP_ID, token.clone());
    phases::mark("backend_selected");
    let daemon_log = paths.as_ref().ok().map(Paths::daemon_log);
    let start = Start {
        safe_mode,
        marker: marker.as_ref(),
        instance: instance.as_ref(),
        // Something to show wants the window in front.
        background: background && show.is_none(),
        show,
    };
    let (error, window_error) = match start.run(paths) {
        Ok(()) => return Ok(()),
        Err(Failure::Explained(error)) => return Err(error),
        Err(Failure::NoWindow { error, window }) => (error, window),
    };
    if renderer == launch::Renderer::Default {
        log::warn!("no window could open ({window_error:#}); trying the software renderer");
        // The retry counts this start itself.
        if let Some(marker) = &marker {
            marker.set(failed_starts);
        }
        // The retry is the first window now.
        drop(instance);
        match launch::retry_in_software(token.as_deref()) {
            Ok(status) if status.success() => return Ok(()),
            Ok(status) => bail!("the software renderer failed too ({status})"),
            Err(e) => log::warn!("could not start again: {e}"),
        }
    }
    launch::report(&window_error, daemon_log.as_deref());
    Err(error)
}

enum Failure {
    /// The error, after a window showed it.
    Explained(anyhow::Error),
    /// The error, and why no window could open to show it.
    NoWindow {
        error: anyhow::Error,
        window: anyhow::Error,
    },
}

/// How this start opens its window.
struct Start<'a> {
    safe_mode: bool,
    marker: Option<&'a launch::Marker>,
    /// Held when this is the first window, which then answers later starts.
    instance: Option<&'a instance::Instance>,
    /// What to show once the window opens.
    show: Option<Show>,
    /// Started at login: in the tray, or minimized on macOS (`launch::showing`).
    background: bool,
}

impl Start<'_> {
    /// The mail window, or the window that says why it could not start.
    fn run(&self, paths: Result<Paths>) -> Result<(), Failure> {
        let (error, paths) = match paths {
            Ok(paths) => match self.open(paths.clone()) {
                Ok(()) => return Ok(()),
                Err(e) => (e, Some(paths)),
            },
            Err(e) => (e, None),
        };
        if launch::no_window(&error) {
            let window = anyhow::anyhow!("{error:#}");
            return Err(Failure::NoWindow { error, window });
        }
        match explain(&error, paths.as_ref(), self.marker) {
            // The first-run form saved an account, so the mail window can open now.
            Ok(true) => self.run(paths.ok_or(error)),
            Ok(false) => Err(Failure::Explained(error)),
            Err(window) if launch::no_window(&window) => Err(Failure::NoWindow { error, window }),
            Err(window) => {
                log::warn!("the startup window failed: {window:#}");
                Err(Failure::Explained(error))
            }
        }
    }

    /// The mail window, until it closes: a config with an account, the daemon, then the window.
    fn open(&self, paths: Paths) -> Result<()> {
        let (safe_mode, marker) = (self.safe_mode, self.marker);
        let config = Config::load(&paths.config_file())?;
        phases::mark("config_loaded");
        if config.accounts.is_empty() {
            bail!(startup::NoAccounts);
        }
        let (client, events, states) = state::connect(&paths, Box::new(wake))?;
        phases::mark("daemon_connected");
        let window = ui::MailWindow::new().context("could not open the window")?;
        launch::watch(window.window(), marker.cloned());
        opener::attach(&window);
        let _scheme = follow_desktop_scheme(&window)?;
        motion::follow(&window);
        let layout = persist::path(&paths);
        if !safe_mode {
            restore(&window, persist::load(&layout));
        }
        let mut app = App::new(&config, paths, client, events, states);
        app.wake = std::sync::Arc::new(wake);
        // Closing the window hides it. The tray keeps the event loop running only while the desktop shows it, so without
        // one closing the window quits, as it always did.
        let tray = ui::Tray::new()
            .inspect_err(|e| log::debug!("no tray icon: {e}"))
            .ok();
        match launch::showing(self.background, tray.is_some(), cfg!(target_os = "macos")) {
            launch::Showing::Front => window.show().context("could not show the window")?,
            launch::Showing::Minimized => {
                window.show().context("could not show the window")?;
                window.window().set_minimized(true);
            }
            launch::Showing::Hidden => {
                // No window to fail, so this start counts as one that worked.
                if let Some(marker) = marker {
                    marker.clear();
                }
            }
        }
        let started = Instant::now();
        let clock = Box::new(move || started.elapsed().as_secs_f64());
        Live::install(
            app,
            window,
            tray,
            Some(postvak_core::badge::Badge::new()),
            clock,
        );
        if let Some(show) = self.show.clone() {
            show_in_window(show);
        }
        if let Some(instance) = self.instance
            && let Err(e) = instance.listen(|request| {
                let _ = slint::invoke_from_event_loop(move || hand_over(request));
            })
        {
            log::warn!("a second start will open a second window: {e}");
        }
        let ran = slint::run_event_loop();
        if let Some(mut live) = LIVE.with_borrow_mut(Option::take) {
            // Without the window there is nobody to keep the count current.
            if let Some(badge) = &mut live.badge {
                badge.show(0);
            }
            // A window that stayed in the tray has no layout of its own to keep.
            if launch::shown()
                && let Err(e) = persist::save(&layout, &remember(&live.window))
            {
                log::warn!("could not save the window's layout: {e:#}");
            }
        }
        ran.context("the window failed")
    }
}

/// The window and the app behind it, owned by the event loop's thread. Daemon events and timers reach it through
/// `wake`, the window's callbacks through `dispatch`.
pub(crate) struct Live {
    pub app: App,
    /// Seconds on the window's clock; tests move it by hand.
    clock: Box<dyn Fn() -> f64>,
    timer: slint::Timer,
    /// None in tests, and where the platform has no tray.
    tray: Option<ui::Tray>,
    /// The unread count on the task bar entry; None in tests.
    badge: Option<postvak_core::badge::Badge>,
    pub window: ui::MailWindow,
}

thread_local! {
    static LIVE: RefCell<Option<Live>> = const { RefCell::new(None) };
    /// Callbacks that ran while `LIVE` was busy, such as an element's `init` during `present`; answered right after.
    static ASKS: RefCell<Vec<bind::Ask>> = const { RefCell::new(Vec::new()) };
}

/// Ticks the app on the event loop's thread; daemon threads call it from anywhere.
fn wake() {
    let _ = slint::invoke_from_event_loop(|| {
        with_live(Live::tick);
    });
}

/// Runs `f` on the live window, unless there is none or it is already in use.
pub(crate) fn with_live<R>(f: impl FnOnce(&mut Live) -> R) -> Option<R> {
    LIVE.with(|live| live.try_borrow_mut().ok()?.as_mut().map(f))
}

/// What a window callback does: `ask` reads the app and names the actions, which are then applied. True when there
/// were any; a callback while the window is busy is answered once it is free, and counts as none.
fn on(ask: bind::Ask) -> bool {
    let mut ask = Some(ask);
    let answered = with_live(|live| ask.take().map(|ask| live.answer(ask)));
    if let Some(ask) = ask {
        ASKS.with_borrow_mut(|asks| asks.push(ask));
    }
    answered.flatten().unwrap_or(false)
}

impl Live {
    /// Takes the app and window for this thread and wires the window's callbacks.
    fn install(
        app: App,
        window: ui::MailWindow,
        tray: Option<ui::Tray>,
        badge: Option<postvak_core::badge::Badge>,
        clock: Box<dyn Fn() -> f64>,
    ) {
        let live = Live {
            app,
            clock,
            timer: slint::Timer::default(),
            tray,
            badge,
            window,
        };
        if let Some(tray) = &live.tray {
            let weak = live.window.as_weak();
            tray.on_open(move || {
                if let Some(window) = weak.upgrade() {
                    raise_from_tray(&window);
                }
            });
            tray.on_sync(|| {
                on(Box::new(|_| vec![state::UiAction::SyncNow]));
            });
            tray.on_quit(|| {
                let _ = slint::quit_event_loop();
            });
        }
        bind::init(&live.window);
        bind::connect(&live.window, on);
        live.window.on_quit(|| {
            let _ = slint::quit_event_loop();
        });
        let weak = live.window.as_weak();
        live.window.on_close_window(move || {
            if let Some(window) = weak.upgrade() {
                let _ = window.hide();
            }
        });
        LIVE.with_borrow_mut(|slot| *slot = Some(live));
        with_live(Live::tick);
    }

    /// Applies what `ask` names, then shows the result; whether it named anything.
    fn answer(&mut self, ask: bind::Ask) -> bool {
        let actions = ask(&self.app);
        let scrolled = actions.iter().all(state::UiAction::is_scroll);
        let answered = self.apply(actions);
        // A scroll comes every frame of a wheel animation and is already on screen, unless the list follows the cursor.
        if !(answered && scrolled && !self.app.list.follow_cursor) {
            self.tick();
        }
        answered
    }

    fn apply(&mut self, actions: Vec<state::UiAction>) -> bool {
        let answered = !actions.is_empty();
        for action in actions {
            self.app.apply(action);
        }
        answered
    }

    /// Time moves the app on, the window shows it, and callbacks that came in meanwhile are answered.
    fn tick(&mut self) {
        loop {
            let now = (self.clock)();
            self.app.tick(now);
            self.present();
            self.follow_theme();
            let asks = ASKS.with_borrow_mut(std::mem::take);
            if asks.is_empty() {
                self.schedule(now);
                return;
            }
            for ask in asks {
                self.apply(ask(&self.app));
            }
        }
    }

    /// HTML mail is styled for the theme the window shows, which only the window knows for System: the window's
    /// answer is asked for after it shows the app's theme choice.
    fn follow_theme(&mut self) {
        let dark = self.window.global::<ui::Theme>().get_dark();
        if dark != self.app.html_dark {
            ASKS.with_borrow_mut(|asks| {
                asks.push(Box::new(move |_| vec![state::UiAction::HtmlDark(dark)]));
            });
        }
    }

    fn present(&mut self) {
        bind::present(&self.app, &self.window);
        if let Some(tray) = &self.tray {
            tray.set_hint(status::tray_hint(&self.app).into());
        }
        if let Some(badge) = &mut self.badge {
            badge.show(folders::inbox_unread(&self.app.accounts));
        }
    }

    /// Starts the timer for the tick the app asked for.
    fn schedule(&mut self, now: f64) {
        if let Some(at) = self.app.next_tick.take() {
            let delay = Duration::from_secs_f64((at - now).max(0.0));
            // Timers fire on the window's thread, so they tick directly.
            self.timer.start(slint::TimerMode::SingleShot, delay, || {
                with_live(Live::tick);
            });
        }
    }
}

/// Shows the window in front of other apps: `show` alone neither activates the app (macOS) nor restores a minimized
/// window. The focus waits a turn of the event loop, for the native window `show` creates.
///
/// Wayland lets no app restore, focus or raise its own window: a window that was hidden comes back as a new one,
/// which the compositor usually puts in front, and one that is open asks for attention, which Plasma shows on its
/// task bar entry and GNOME as "Postvak is ready".
fn raise(window: &ui::MailWindow) {
    if let Err(e) = window.show() {
        log::warn!("could not show the window: {e}");
        return;
    }
    window.window().set_minimized(false);
    let weak = window.as_weak();
    slint::Timer::single_shot(Duration::ZERO, move || {
        if let Some(window) = weak.upgrade() {
            window.window().with_winit_window(|native| {
                native.focus_window();
                if on_wayland(native) {
                    native.request_user_attention(Some(
                        slint::winit_030::winit::window::UserAttentionType::Informational,
                    ));
                }
            });
        }
    });
}

/// On Wayland a click on the tray comes with an activation token, which Slint gives the next native window it creates,
/// and Plasma keeps a launch entry on its task bar until a window uses it. So an open window comes back as a new one,
/// which the token brings to the front.
fn raise_from_tray(window: &ui::MailWindow) {
    let wayland = window
        .window()
        .with_winit_window(on_wayland)
        .unwrap_or(false);
    if !wayland {
        raise(window);
        return;
    }
    if let Err(e) = window.hide().and_then(|()| window.show()) {
        log::warn!("could not show the window: {e}");
    }
}

fn on_wayland(native: &slint::winit_030::winit::window::Window) -> bool {
    use slint::winit_030::winit::raw_window_handle::{HasWindowHandle, RawWindowHandle};
    native
        .window_handle()
        .is_ok_and(|handle| matches!(handle.as_raw(), RawWindowHandle::Wayland(_)))
}

/// Shows the message, or the Rules view, in the window.
fn show_in_window(show: Show) {
    let action = match show {
        Show::Message(open) => state::UiAction::OpenMessage(open),
        Show::Rules => state::UiAction::SelectView(state::View::Rules),
    };
    on(Box::new(move |_| vec![action]));
}

/// A later start's request: show what it asks for, then bring the window to the front.
fn hand_over(request: instance::Request) {
    if let Some(show) = request.show {
        show_in_window(show);
    }
    let window = with_live(|live| live.window.as_weak()).and_then(|weak| weak.upgrade());
    if let Some(window) = window {
        raise(&window);
    }
}

/// Tells the window whether the desktop is dark, now and whenever that changes, for the System theme. The probe
/// must live as long as the window.
fn follow_desktop_scheme(window: &ui::MailWindow) -> Result<ui::SchemeProbe> {
    let probe = ui::SchemeProbe::new().context("could not open the window")?;
    window
        .global::<ui::Theme>()
        .set_desktop_dark(probe.get_dark());
    let weak = window.as_weak();
    probe.on_dark_changed(move |dark| {
        if let Some(window) = weak.upgrade() {
            window.global::<ui::Theme>().set_desktop_dark(dark);
        }
        // A tick, so HTML mail follows the System theme (`Live::follow_theme`).
        on(Box::new(|_| Vec::new()));
    });
    Ok(probe)
}

/// Sizes the window and its panes as they were last time.
fn restore(window: &ui::MailWindow, layout: Option<persist::Layout>) {
    let Some(layout) = layout else { return };
    // Small enough for any screen, large enough to use.
    let (width, height) = (layout.width.max(400.0), layout.height.max(300.0));
    window
        .window()
        .set_size(slint::LogicalSize::new(width, height));
    if let Some((x, y)) = layout.position {
        window
            .window()
            .set_position(slint::PhysicalPosition::new(x, y));
    }
    window.set_folders_width(layout.folders_width.max(theme::CONTROL));
    window.set_list_width(layout.list_width.max(list::MIN_WIDTH));
}

/// The window's layout, to be restored next time.
fn remember(window: &ui::MailWindow) -> persist::Layout {
    let size = window
        .window()
        .size()
        .to_logical(window.window().scale_factor());
    let position = window.window().position();
    persist::Layout {
        width: size.width,
        height: size.height,
        position: (position.x != 0 || position.y != 0).then_some((position.x, position.y)),
        folders_width: window.get_folders_width(),
        list_width: window.get_list_width(),
    }
}

/// Shows why the mail window could not start until the user closes it; the caller prints the error and sets the exit
/// code. With no account yet and paths to save under, the window holds the add-account form: true when it saved one.
/// Without a display there is no window, and stderr is all there is. The window remembers nothing.
fn explain(
    error: &anyhow::Error,
    paths: Option<&Paths>,
    marker: Option<&launch::Marker>,
) -> Result<bool> {
    let log = paths.map(Paths::daemon_log);
    let mut problem = startup::Problem::of(error, log.as_deref());
    let crashes = paths.map(Paths::crash_dir);
    if let Some(dir) = crashes.filter(|dir| has_crashes(dir) && !error.is::<startup::NoAccounts>())
    {
        problem = problem.with_crashes(&dir);
    }
    let open_docs = |url: &str| {
        if let Err(e) = opener::open(url.as_ref(), false) {
            log::warn!("could not open the docs: {e}");
        }
    };
    let form = paths.filter(|_| error.is::<startup::NoAccounts>()).cloned();
    let pending = Pending::default();
    let window = startup_window(
        &problem,
        open_docs,
        form.clone(),
        pending.clone(),
        state::test_login,
    )?;
    launch::watch(window.window(), marker.cloned());
    opener::attach(&window);
    window.run()?;
    Ok(form.is_some_and(|paths| saved(&paths, &pending)))
}

fn has_crashes(dir: &std::path::Path) -> bool {
    postvak_core::crash::list(dir).is_ok_and(|ids| !ids.is_empty())
}

/// The first-run form's save in flight, if any.
type Pending = Rc<RefCell<Option<Save>>>;

/// A save's steps, and whether its login test passed already.
struct Save {
    answer: account::Saving,
    tested: bool,
}

/// Whether config.toml holds an account once the window closed. A save still testing the login gives up, as its steps
/// are dropped and nothing is saved yet; one past the test is waited for, since closing the window does not stop it.
fn saved(paths: &Paths, pending: &Pending) -> bool {
    if let Some(mut save) = pending.take() {
        let finished = loop {
            match worker::poll(&save.answer) {
                Some(Ok(account::Step::Tested)) => save.tested = true,
                Some(_) => break true,
                None => break false,
            }
        };
        if !finished && save.tested {
            let _ = save.answer.recv();
        }
    }
    Config::load(&paths.config_file()).is_ok_and(|config| !config.accounts.is_empty())
}

/// The window that says what went wrong. With `form`, the paths to save under, it holds the add-account form, and
/// `pending` holds its save while it runs; `check` tests the login before it saves.
fn startup_window(
    problem: &startup::Problem,
    open_docs: impl Fn(&str) + 'static,
    form: Option<Paths>,
    pending: Pending,
    check: account::Check,
) -> Result<ui::StartupWindow, slint::PlatformError> {
    let window = ui::StartupWindow::new()?;
    window.set_summary(problem.summary.as_str().into());
    window.set_fix(problem.fix.as_str().into());
    window.set_detail(problem.detail.as_deref().unwrap_or_default().into());
    let (label, url) = problem.link.unwrap_or_default();
    window.set_link_label(label.into());
    window.set_link_url(url.into());
    window.on_open_url(move |url| open_docs(&url));
    let weak = window.as_weak();
    window.on_close_clicked(move || {
        if let Some(window) = weak.upgrade() {
            let _ = window.hide();
        }
    });
    window.set_form(form.is_some());
    if let Some(paths) = form {
        let weak = window.as_weak();
        window.on_save_account(move |fields| {
            let Some(window) = weak.upgrade() else { return };
            let fields = bind::account_fields(fields);
            match account::save(paths.clone(), &fields, Arc::new(|| {}), check) {
                Ok(answer) => {
                    window.set_account_error(SharedString::new());
                    window.set_account_saving(true);
                    window.set_account_progress(account::progress(true).into());
                    pending.replace(Some(Save {
                        answer,
                        tested: false,
                    }));
                    await_save(&window, pending.clone());
                }
                Err(message) => window.set_account_error(message.into()),
            }
        });
    }
    Ok(window)
}

/// How often the first-run window looks for the save's answer.
const SAVE_POLL: Duration = Duration::from_millis(100);

/// Looks for the save's steps every `SAVE_POLL`: a saved account closes the window, a refusal shows why.
fn await_save(window: &ui::StartupWindow, pending: Pending) {
    let weak = window.as_weak();
    slint::Timer::single_shot(SAVE_POLL, move || {
        let Some(window) = weak.upgrade() else { return };
        let Some(mut save) = pending.take() else {
            return;
        };
        let refused = loop {
            match worker::poll(&save.answer) {
                None => {
                    pending.replace(Some(save));
                    return await_save(&window, pending);
                }
                Some(Ok(account::Step::Tested)) => {
                    save.tested = true;
                    window.set_account_progress(account::progress(false).into());
                }
                Some(Ok(account::Step::Saved(_))) => {
                    let _ = window.hide();
                    return;
                }
                Some(Ok(account::Step::Refused(why))) => break why,
                Some(Err(worker::Stopped)) => break account::STOPPED.into(),
            }
        };
        window.set_account_saving(false);
        window.set_account_error(refused.into());
    });
}

